type FrettedInstrument = 'guitar' | 'bass'
type Event = readonly [midi: number, beat: number, beats?: number, velocity?: number]
type ChordHit = readonly [beat: number, pitches: readonly number[], beats: number, velocity?: number]

const chordHits = (...hits: ChordHit[]): Event[] =>
  hits.flatMap(([beat, pitches, beats, velocity = 0.9]) =>
    pitches.map((midi) => [midi, beat, beats, velocity] as Event))

