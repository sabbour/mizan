const study = (item: Study): PianoLesson => {
  const arranged = arrange({
    id: item.id,
    chords: item.chords,
    ...item.phrase,
    fills: item.fill,
    pedal: item.pedal ?? item.phrase.pedal,
  })
  const dynamics = item.dynamics ?? expressive[item.level]
  const notes = arranged.notes.map((note) => {
    const bar = Math.floor(note.startBeat / item.phrase.beatsPerBar)
    const beat = note.startBeat - bar * item.phrase.beatsPerBar
    const midi = item.leftPedal && note.hand === 'left'
      ? item.leftPedal.midi + (bar >= item.leftPedal.octaveBar && beat >= item.leftPedal.octaveBeat ? 12 : 0)
      : note.midi
    const velocity = Math.min(0.95, Math.max(0.35, (note.velocity ?? 0.6) + dynamics[bar]))
    return { ...note, midi, velocity }
  })
  return {
    ...item,
    notes,
    ...(arranged.fills.length ? { fills: arranged.fills } : {}),
    ...(arranged.pedals ? { pedals: arranged.pedals } : {}),
  }
}

